/**
 * Tra cứu địa điểm theo từ khóa, danh mục hoặc tỉnh thành
 */
export function searchNationalPlaces(
  query = '',
  categoryType: NationalCategoryType | 'all' = 'all',
  province = ''
): NationalPlace[] {
  let list = MASTER_NATIONWIDE_PLACES;

  if (categoryType !== 'all') {
    list = list.filter((p) => p.categoryType === categoryType);
  }

  if (province) {
    list = list.filter((p) =>
      p.province.toLowerCase().includes(province.toLowerCase())
    );
  }

  if (query.trim()) {
    const q = query.toLowerCase().trim();
    list = list.filter(
      (p) =>
        p.name.toLowerCase().includes(q) ||
        p.category.toLowerCase().includes(q) ||
        p.district.toLowerCase().includes(q) ||
        p.address.toLowerCase().includes(q) ||
        p.desc.toLowerCase().includes(q)
    );
  }

  return list;
}
